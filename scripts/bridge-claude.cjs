#!/usr/bin/env node
/**
 * Makes the skills in .agent/skills/ discoverable by Claude Code.
 *
 * Claude Code only finds skills under .claude/skills/. For each
 * .agent/skills/<name>/SKILL.md this writes a thin stub at
 * .claude/skills/vibe-<name>/SKILL.md that carries the same description and
 * points at the real file, so there is one source of truth and no copy to
 * drift. The `vibe-` prefix avoids collisions with built-in or existing
 * skills (`code-review`, `git`, ...).
 *
 * Touches only .claude/skills/vibe-* directories; stubs whose source skill
 * is gone are removed. Idempotent.
 *
 * Usage: node scripts/bridge-claude.cjs   (no arguments)
 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, ".agent", "skills");
const OUT = path.join(ROOT, ".claude", "skills");
const PREFIX = "vibe-";
const MARKER = "GENERATED by scripts/bridge-claude.cjs";

// The `description:` value from a SKILL.md frontmatter: plain, quoted, or a
// folded/literal block (`>` or `|`).
function readDescription(text) {
  const fm = text.match(/^---\n([\s\S]*?)\n---/);
  if (!fm) return null;
  const lines = fm[1].split("\n");
  const i = lines.findIndex((l) => /^description:/.test(l));
  if (i === -1) return null;
  let value = lines[i].replace(/^description:\s*/, "");
  if (/^[>|][+-]?\s*$/.test(value)) {
    const block = [];
    for (let j = i + 1; j < lines.length && /^(\s+\S|\s*$)/.test(lines[j]); j++) block.push(lines[j].trim());
    value = block.join(" ");
  }
  return value.replace(/^["'](.*)["']$/, "$1").replace(/\s+/g, " ").trim() || null;
}

function main() {
  if (process.argv.length > 2) {
    console.log("usage: node scripts/bridge-claude.cjs");
    console.log("Writes .claude/skills/vibe-<name>/SKILL.md stubs for .agent/skills/. Takes no arguments.");
    process.exit(/^(-h|--help)$/.test(process.argv[2]) ? 0 : 2);
  }
  if (!fs.existsSync(SRC)) {
    console.error(`[vibe] ${path.relative(ROOT, SRC)} not found — nothing to bridge.`);
    process.exit(1);
  }

  const wanted = new Set();
  for (const name of fs.readdirSync(SRC).sort()) {
    const source = path.join(SRC, name, "SKILL.md");
    if (!fs.existsSync(source)) continue; // _shared/ and README.md have none
    const description = readDescription(fs.readFileSync(source, "utf8"));
    if (!description) {
      console.error(`[vibe] ${path.relative(ROOT, source)} has no description — skipped.`);
      continue;
    }
    const stubName = PREFIX + name;
    wanted.add(stubName);
    const rel = `.agent/skills/${name}/SKILL.md`;
    const body = `---
name: ${stubName}
description: ${JSON.stringify(description)}
---
<!-- ${MARKER} from ${rel} — do not hand-edit. -->

Read \`${rel}\` and follow it exactly. Files it names under \`_shared/\`
are in \`.agent/skills/_shared/\`. Start by stating the ceremony tier, as
\`AGENTS.md\` requires.
`;
    const dir = path.join(OUT, stubName);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "SKILL.md"), body);
  }

  // Remove our own stale stubs, and nothing else.
  if (fs.existsSync(OUT)) {
    for (const name of fs.readdirSync(OUT)) {
      if (!name.startsWith(PREFIX) || wanted.has(name)) continue;
      const stub = path.join(OUT, name, "SKILL.md");
      if (fs.existsSync(stub) && fs.readFileSync(stub, "utf8").includes(MARKER)) {
        fs.unlinkSync(stub);
        if (fs.readdirSync(path.join(OUT, name)).length === 0) fs.rmdirSync(path.join(OUT, name));
      }
    }
  }

  console.log(`[vibe] bridged ${wanted.size} skill(s) -> .claude/skills/`);
  for (const n of [...wanted].sort()) console.log(`  ${n}`);
}

main();
